# Приоритет уровней (для прохода)
LEVEL_ORDER = ("critical", "help", "bad", "ok", "good")

# Уровни, о которых надо уведомлять семью
ALERT_LEVELS = {"critical", "help", "bad"}


def classify(text: str) -> str | None:
    """
    Возвращает уровень самочувствия или None, если не распознано.
    Приоритет: critical > help > bad > ok > good.
    """
    if not text:
        return None
    norm = re.sub(r"[^\w\sА-Яа-яЁё]", " ", text.lower())
    for level in LEVEL_ORDER:
        for word in LEVELS[level]:
            if word in norm:
                return level
    return None


def is_alert(level: str | None) -> bool:
    """Нужно ли слать тревогу семье при таком уровне."""
    return level in ALERT_LEVELS