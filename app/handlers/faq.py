@router.message(F.text == "❓ Как пользоваться ботом?")
async def faq_root(msg: Message):
    user = await get_user_by_tg(msg.from_user.id)
    is_elderly = False
    if user:
        is_elderly = bool(await get_elderly_by_user(user.id))

    if is_elderly:
        await msg.answer("❓ <b>Как пользоваться ботом?</b>",
                         reply_markup=kb_faq_elderly())
    else:
        await msg.answer("❓ <b>Как пользоваться ботом?</b>",
                         reply_markup=kb_faq_family())


@router.callback_query(F.data == "faq:close")
async def faq_close(cb: CallbackQuery):
    await cb.message.edit_text("Справка закрыта.")
    await cb.answer()


