@router.callback_query(F.data.startswith("faq:fam:"))
async def faq_family_section(cb: CallbackQuery):
    key = cb.data.split(":")[-1]
    text = FAQ_FAMILY.get(key)
    if not text:
        await cb.answer("Раздел не найден", show_alert=True)
        return
    await cb.message.edit_text(text, reply_markup=kb_faq_back(is_family=True))
    await cb.answer()


